/**
 * スプライトの形を確かめる。問題があれば日本語の説明を並べて返す(問題がなければ空の配列)。
 * - 1 行以上ある / すべての行の長さが同じ / 使っている文字が透明か色の対応表にある
 */
export function validateSprite(rows, palette) {
  if (!Array.isArray(rows) || rows.length === 0) return ["行がありません"];
  const width = rows[0].length;
  if (width === 0) return ["1 行目が空です"];
  return rows.flatMap((row, y) => {
    const lengthErrors = row.length === width ? [] : [`${y + 1} 行目の長さが ${row.length}(${width} のはず)`];
    const unknown = [...new Set(row)].filter((ch) => ch !== TRANSPARENT && !(ch in palette));
    const colorErrors = unknown.map((ch) => `${y + 1} 行目の「${ch}」は色の対応表にありません`);
    return [...lengthErrors, ...colorErrors];
  });
}

/** スプライトの幅と高さ(ドット)。 */
export const spriteSize = (rows) => ({ width: rows[0]?.length ?? 0, height: rows.length });

/** ドットの文字で書いたときの幅(ドット)。文字の間は 1 ドットあける。 */
export function textWidth(text, scale = 1) {
  const count = [...text].length;
  return count === 0 ? 0 : (count * (FONT_WIDTH + 1) - 1) * scale;
}

/** FONT にない文字を除いた文字列(小文字の x 以外は大文字にそろえる)。 */
export function toFontText(text) {
  return [...String(text)]
    .map((ch) => (ch === "x" || ch === "×" ? "x" : ch.toUpperCase()))
    .filter((ch) => ch in FONT)
    .join("");
}
